interface LanguageContextType {
  currentLang: LanguageOption;
  setLanguage: (code: LanguageCode) => void;
  t: (key: string) => string;
}

const LanguageContext = createContext<LanguageContextType>({
  currentLang: LANGUAGES[0],
  setLanguage: () => {},
  t: (key: string) => key,
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [currentLang, setCurrentLangState] = useState<LanguageOption>(LANGUAGES[0]);

  useEffect(() => {
    try {
      const saved = localStorage.getItem('cardbyte_lang') as LanguageCode;
      if (saved) {
        const found = LANGUAGES.find(l => l.code === saved);
        if (found) {
          setCurrentLangState(found);
          document.documentElement.lang = found.code;
          document.documentElement.dir = found.dir;
        }
      }
    } catch {}
  }, []);

  const setLanguage = (code: LanguageCode) => {
    const found = LANGUAGES.find(l => l.code === code);
    if (found) {
      setCurrentLangState(found);
      try {
        localStorage.setItem('cardbyte_lang', code);
      } catch {}
      document.documentElement.lang = found.code;
      document.documentElement.dir = found.dir;
    }
  };

  const t = (key: string): string => {
    const dict = TRANSLATIONS[currentLang.code] || TRANSLATIONS.en;
    if (dict[key]) return dict[key];
    const enDict = TRANSLATIONS.en;
    return enDict[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ currentLang, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
